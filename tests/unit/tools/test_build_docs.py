from __future__ import annotations

from pathlib import Path

import click
import pytest

from dripleg.cli.main import cli
from dripleg.tools.build_docs import DEFAULT_PATH, main, missing_help, render, walk


def test_every_command_in_the_build_is_documented() -> None:
    text = render(cli)
    for path, _ in walk(cli):
        assert f"## `{path}`" in text


def test_the_walk_finds_the_nested_groups() -> None:
    paths = [path for path, _ in walk(cli)]
    assert "dripleg trap add" in paths
    assert "dripleg work verify" in paths
    assert "dripleg about" in paths
    assert paths == sorted(paths)


def test_every_command_has_a_help_line_and_every_option_has_help() -> None:
    assert missing_help(cli) == []


def test_a_command_without_help_is_caught() -> None:
    @click.group()
    def group() -> None:
        """A group."""

    @group.command("bare")
    def bare() -> None:
        pass

    problems = missing_help(group)
    assert problems == ["dripleg bare has no help line"]


def test_an_option_without_help_is_caught() -> None:
    @click.group()
    def group() -> None:
        """A group."""

    @group.command("thing")
    @click.option("--quiet", is_flag=True)
    def thing(quiet: bool) -> None:
        """Do a thing."""

    problems = missing_help(group)
    assert problems == ["dripleg thing option --quiet has no help text"]


def test_the_help_and_version_options_are_not_required_to_carry_help() -> None:
    assert not any("--help" in problem for problem in missing_help(cli))
    assert not any("--version" in problem for problem in missing_help(cli))


def test_the_rendered_reference_says_it_is_generated() -> None:
    text = render(cli)
    assert text.startswith("<!-- generated by")
    assert "# Commands" in text
    assert text.endswith("\n")


def test_arguments_are_listed_as_positional() -> None:
    text = render(cli)
    assert "| `tag` | positional |" in text


def test_rendering_is_stable() -> None:
    assert render(cli) == render(cli)


def test_the_checked_in_reference_is_up_to_date() -> None:
    assert DEFAULT_PATH.exists()
    assert DEFAULT_PATH.read_text(encoding="utf-8") == render(cli)


def test_the_gate_writes_the_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "nested" / "commands.md"
    assert main(["--path", str(target)]) == 0
    assert target.exists()
    assert "wrote" in capsys.readouterr().out


def test_the_gate_passes_a_fresh_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "commands.md"
    main(["--path", str(target)])
    assert main(["--path", str(target), "--check"]) == 0
    assert "up to date" in capsys.readouterr().out


def test_the_gate_fails_a_stale_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "commands.md"
    target.write_text("out of date\n", encoding="utf-8")
    assert main(["--path", str(target), "--check"]) == 1
    assert "out of date" in capsys.readouterr().err


def test_the_gate_fails_a_missing_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["--path", str(tmp_path / "nope.md"), "--check"]) == 1
    assert "is missing" in capsys.readouterr().err
