from __future__ import annotations

from pathlib import Path

import pytest

from dripleg.store.db import Database
from dripleg.store.migrations import migrate
from dripleg.tools.schema_dump import (
    DEFAULT_PATH,
    TableSchema,
    current,
    main,
    read_schema,
    render,
)


def read_schema_of_a_migrated_book() -> list[TableSchema]:
    with Database() as book:
        migrate(book)
        return read_schema(book)


def test_every_table_in_the_book_is_described() -> None:
    tables = read_schema_of_a_migrated_book()
    names = {table.name for table in tables}
    assert {"site", "trap_station", "observation", "work_order"} <= names


def test_a_table_knows_which_columns_are_required() -> None:
    tables = {t.name: t for t in read_schema_of_a_migrated_book()}
    site = tables["site"]
    assert "code" in site.required_columns
    assert "name" in site.required_columns


def test_a_table_counts_its_check_constraints() -> None:
    tables = {t.name: t for t in read_schema_of_a_migrated_book()}
    assert tables["work_order"].checks >= 5
    assert tables["schema_migration"].checks == 0


def test_indexes_are_listed_and_the_internal_ones_are_not() -> None:
    tables = {t.name: t for t in read_schema_of_a_migrated_book()}
    assert "station_by_header" in tables["trap_station"].indexes
    assert all(not name.startswith("sqlite_") for name in tables["site"].indexes)


def test_the_rendered_markdown_says_it_is_generated() -> None:
    text = current()
    assert text.startswith("<!-- generated by")
    assert "do not edit by hand" in text
    assert "# Schema" in text


def test_the_rendered_markdown_has_a_section_per_table() -> None:
    text = current()
    for name in ("site", "area", "header", "trap_station", "work_order"):
        assert f"## {name}" in text


def test_rendering_is_stable() -> None:
    assert current() == current()


def test_the_checked_in_file_is_up_to_date() -> None:
    assert DEFAULT_PATH.exists()
    assert DEFAULT_PATH.read_text(encoding="utf-8") == current()


def test_the_gate_writes_the_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "nested" / "schema.md"
    assert main(["--path", str(target)]) == 0
    assert target.exists()
    assert "wrote" in capsys.readouterr().out


def test_the_gate_passes_a_fresh_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "schema.md"
    main(["--path", str(target)])
    assert main(["--path", str(target), "--check"]) == 0
    assert "up to date" in capsys.readouterr().out


def test_the_gate_fails_a_stale_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = tmp_path / "schema.md"
    target.write_text("something else\n", encoding="utf-8")
    assert main(["--path", str(target), "--check"]) == 1
    assert "out of date" in capsys.readouterr().err


def test_the_gate_fails_a_missing_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["--path", str(tmp_path / "nope.md"), "--check"]) == 1
    assert "is missing" in capsys.readouterr().err


def test_rendering_an_empty_schema() -> None:
    text = render([])
    assert "0 tables" in text
    assert text.endswith("\n")
