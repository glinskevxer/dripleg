"""Write the schema out as markdown, and fail the build when it drifts.

The schema is the thing an integrator reads first and it is the thing nobody
remembers to document. So it is generated from the migrations, checked in, and
CI runs the same generator with `--check` and diffs it. A schema change with no
matching documentation change is a red build rather than a surprise six months
later.

The generated file carries a header saying it is generated, because the second
most likely outcome is somebody editing it by hand.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from dripleg.store.db import Database
from dripleg.store.migrations import MIGRATIONS, migrate

__all__ = [
    "DEFAULT_PATH",
    "TableSchema",
    "main",
    "read_schema",
    "render",
]

DEFAULT_PATH = Path("docs/schema.md")

HEADER = "<!-- generated by python -m dripleg.tools.schema_dump. do not edit by hand. -->\n"

_TYPE = re.compile(r"^\s*(?P<name>[a-z_]+)\s+(?P<type>[A-Z]+)")


@dataclass(frozen=True)
class TableSchema:
    """One table, its columns and the indexes on it."""

    name: str
    columns: list[tuple[str, str, bool]]
    indexes: list[str]
    checks: int

    @property
    def required_columns(self) -> list[str]:
        return [name for name, _, required in self.columns if required]


def read_schema(book: Database) -> list[TableSchema]:
    """Pull the shape of every table out of a migrated book."""

    tables: list[TableSchema] = []
    for name in book.table_names():
        columns = [
            (str(row["name"]), str(row["type"]), bool(row["notnull"]) or bool(row["pk"]))
            for row in book.query(f"PRAGMA table_info({name})")
        ]
        indexes = sorted(
            str(row["name"])
            for row in book.query(f"PRAGMA index_list({name})")
            if not str(row["name"]).startswith("sqlite_")
        )
        sql = str(book.scalar("SELECT sql FROM sqlite_master WHERE name = ?", (name,)) or "")
        tables.append(
            TableSchema(
                name=name,
                columns=columns,
                indexes=indexes,
                checks=sql.upper().count("CHECK ("),
            )
        )
    return tables


def render(tables: list[TableSchema]) -> str:
    """The markdown this build expects to find checked in."""

    lines = [HEADER, "# Schema", ""]
    lines.append(f"{len(MIGRATIONS)} migrations, {len(tables)} tables.")
    lines.append("")
    for table in tables:
        lines.append(f"## {table.name}")
        lines.append("")
        lines.append("| column | type | required |")
        lines.append("| --- | --- | --- |")
        for name, kind, required in table.columns:
            lines.append(f"| {name} | {kind or 'ANY'} | {'yes' if required else 'no'} |")
        lines.append("")
        if table.indexes:
            lines.append(f"Indexes: {', '.join(table.indexes)}.")
            lines.append("")
        if table.checks:
            lines.append(f"{table.checks} check constraints.")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def current() -> str:
    with Database() as book:
        migrate(book)
        return render(read_schema(book))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write or check the schema documentation.")
    parser.add_argument("--path", default=DEFAULT_PATH, type=Path)
    parser.add_argument("--check", action="store_true", help="Fail if the file is stale.")
    args = parser.parse_args(argv)
    wanted = current()
    if not args.check:
        args.path.parent.mkdir(parents=True, exist_ok=True)
        args.path.write_text(wanted, encoding="utf-8")
        print(f"wrote {args.path}")
        return 0
    if not args.path.exists():
        print(f"{args.path} is missing, run this without --check", file=sys.stderr)
        return 1
    if args.path.read_text(encoding="utf-8") != wanted:
        print(
            f"{args.path} is out of date, run python -m dripleg.tools.schema_dump",
            file=sys.stderr,
        )
        return 1
    print(f"{args.path} is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
