"""Write the command reference out of the click tree, and check it in CI.

A command reference maintained by hand is a command reference that is wrong.
This walks the group, takes each command's help text and options straight off
the objects click already built, and writes markdown. CI runs it with
`--check`, so adding a command without documenting it is a red build.

It also enforces two house rules that a reviewer would otherwise have to notice
by eye: every command has a help line, and every option has help text. Both are
the sort of thing that gets left off at five o'clock and never comes back.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import click

from dripleg.cli.main import cli

__all__ = ["DEFAULT_PATH", "main", "missing_help", "render", "walk"]

DEFAULT_PATH = Path("docs/commands.md")

HEADER = "<!-- generated by python -m dripleg.tools.build_docs. do not edit by hand. -->\n"


def walk(group: click.Group, prefix: str = "dripleg") -> list[tuple[str, click.Command]]:
    """Every command under a group, in the order it should be printed."""

    found: list[tuple[str, click.Command]] = []
    for name in sorted(group.commands):
        command = group.commands[name]
        path = f"{prefix} {name}"
        if isinstance(command, click.Group):
            found.extend(walk(command, path))
        else:
            found.append((path, command))
    return found


def _options(command: click.Command) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for parameter in command.params:
        if isinstance(parameter, click.Option):
            flags = ", ".join(parameter.opts)
            default = "" if parameter.default in (None, False) else str(parameter.default)
            rows.append((flags, parameter.help or "", default))
        elif isinstance(parameter, click.Argument):
            rows.append((parameter.name or "", "positional", ""))
    return rows


def missing_help(group: click.Group) -> list[str]:
    """Commands with no help line, and options with no help text."""

    problems: list[str] = []
    for path, command in walk(group):
        if not (command.help or command.short_help):
            problems.append(f"{path} has no help line")
        for parameter in command.params:
            if isinstance(parameter, click.Option) and not parameter.help:
                if parameter.name in {"help", "version"}:
                    continue
                problems.append(f"{path} option {parameter.opts[0]} has no help text")
    return problems


def render(group: click.Group) -> str:
    commands = walk(group)
    lines = [HEADER, "# Commands", "", f"{len(commands)} commands.", ""]
    for path, command in commands:
        lines.append(f"## `{path}`")
        lines.append("")
        summary = (command.help or command.short_help or "").strip().splitlines()
        lines.append(summary[0] if summary else "")
        lines.append("")
        rows = _options(command)
        if rows:
            lines.append("| option | help | default |")
            lines.append("| --- | --- | --- |")
            for flags, help_text, default in rows:
                lines.append(f"| `{flags}` | {help_text} | {default} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write or check the command reference.")
    parser.add_argument("--path", default=DEFAULT_PATH, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    problems = missing_help(cli)
    if problems:
        for line in problems:
            print(line, file=sys.stderr)
        return 1
    wanted = render(cli)
    if not args.check:
        args.path.parent.mkdir(parents=True, exist_ok=True)
        args.path.write_text(wanted, encoding="utf-8")
        print(f"wrote {args.path}")
        return 0
    if not args.path.exists():
        print(f"{args.path} is missing, run this without --check", file=sys.stderr)
        return 1
    if args.path.read_text(encoding="utf-8") != wanted:
        print(
            f"{args.path} is out of date, run python -m dripleg.tools.build_docs",
            file=sys.stderr,
        )
        return 1
    print(f"{args.path} is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
